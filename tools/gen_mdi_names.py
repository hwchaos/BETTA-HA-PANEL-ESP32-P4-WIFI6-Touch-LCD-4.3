"""Generate main/ui/fonts/mdi_names.c: a sorted table mapping Material Design
Icons names ("desk", "power-socket-de", ...) to their codepoints, read from the
glyph names ('post' table, format 2.0) and the character map of
materialdesignicons-webfont.ttf. Standard library only.

    python tools/gen_mdi_names.py main/ui/fonts/materialdesignicons-webfont.ttf main/ui/fonts/mdi_names.c
"""
import struct
import sys

MAC_GLYPHS = 258  # format 2.0 indices below this refer to the standard Mac glyph set


def tables(data):
    count = struct.unpack_from(">H", data, 4)[0]
    out = {}
    for i in range(count):
        tag, _, off, length = struct.unpack_from(">4sIII", data, 12 + 16 * i)
        out[tag.decode("latin-1")] = (off, length)
    return out


def glyph_names(data, off):
    fmt = struct.unpack_from(">I", data, off)[0]
    if fmt != 0x00020000:
        raise SystemExit("post table format %#x not supported" % fmt)
    num = struct.unpack_from(">H", data, off + 32)[0]
    idx = struct.unpack_from(">%dH" % num, data, off + 34)
    pos = off + 34 + 2 * num
    pascal = []
    while len(pascal) < max([i - MAC_GLYPHS for i in idx if i >= MAC_GLYPHS] + [-1]) + 1:
        n = data[pos]
        pascal.append(data[pos + 1:pos + 1 + n].decode("ascii"))
        pos += 1 + n
    return {gid: pascal[i - MAC_GLYPHS] for gid, i in enumerate(idx) if i >= MAC_GLYPHS}


def char_map(data, off):
    num = struct.unpack_from(">H", data, off + 2)[0]
    best = None
    for i in range(num):
        pid, eid, sub = struct.unpack_from(">HHI", data, off + 4 + 8 * i)
        fmt = struct.unpack_from(">H", data, off + sub)[0]
        if fmt == 12:
            best = off + sub
            break
    if best is None:
        raise SystemExit("no format 12 cmap subtable")
    groups = struct.unpack_from(">I", data, best + 12)[0]
    gid_to_cp = {}
    for g in range(groups):
        start, end, gid0 = struct.unpack_from(">III", data, best + 16 + 12 * g)
        for cp in range(start, end + 1):
            gid_to_cp.setdefault(gid0 + cp - start, cp)
    return gid_to_cp


def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    t = tables(data)
    names = glyph_names(data, t["post"][0])
    cps = char_map(data, t["cmap"][0])
    pairs = sorted((name, cps[gid]) for gid, name in names.items() if gid in cps and cps[gid] >= 0xF0000)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* SPDX-License-Identifier: LicenseRef-FNCL-1.1 */\n")
        f.write("/* Generated by tools/gen_mdi_names.py from materialdesignicons-webfont.ttf - do not edit. */\n")
        f.write('#include "ui/fonts/mdi_names.h"\n\n')
        f.write("const mdi_name_entry_t g_mdi_names[] = {\n")
        for name, cp in pairs:
            f.write('    {"%s", 0x%05X},\n' % (name, cp))
        f.write("};\n\n")
        f.write("const size_t g_mdi_names_count = sizeof(g_mdi_names) / sizeof(g_mdi_names[0]);\n")
    print("%d icons" % len(pairs))


if __name__ == "__main__":
    main()
